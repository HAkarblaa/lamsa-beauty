let language = 'ar';
try { if (localStorage.getItem('lamsa-language') === 'en') language = 'en'; }
catch { /* The default language remains available. */ }

function translate(value) {
  if (language !== 'en') return value;
  if (Object.hasOwn(english,value)) return english[value];
  const patterns = [
    [/^عرض (\d+)$/, 'Slide $1'], [/^المتوفر (.+)$/, 'Available: $1'],
    [/^الكمية (.+)$/, 'Quantity: $1'], [/^الترتيب (.+)$/, 'Position: $1'],
    [/^(\d+) قسم$/, '$1 categories'], [/^(\d+) منتج$/, '$1 products'],
    [/^(\d+) إعلان$/, '$1 banners'], [/^(\d+) طلب قيد المتابعة$/, '$1 pending orders'],
    [/^لوحة إدارة (.+)$/, 'Admin dashboard · $1']
  ];
  for (const [pattern,replacement] of patterns) {
    if (pattern.test(value)) return value.replace(pattern,replacement);
  }
  return value;
}

function localize(root) {
  const walker = document.createTreeWalker(root,NodeFilter.SHOW_TEXT);
  for (let node = walker.nextNode(); node; node = walker.nextNode()) {
    const text = node.nodeValue.trim();
    const localized = translate(text);
    if (text && localized !== text) node.nodeValue = node.nodeValue.replace(text,localized);
  }
  for (const element of root.querySelectorAll('[aria-label],[placeholder],[alt]')) {
    for (const attribute of ['aria-label','placeholder','alt']) {
      if (element.hasAttribute(attribute)) element.setAttribute(attribute,translate(element.getAttribute(attribute)));
    }
  }
}
